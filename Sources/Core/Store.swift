import Foundation

/// Meetings on disk: one folder per meeting with meeting.json + transcript.md + summary.md + audio.
public enum Store {
    public static func folder(_ id: String) -> URL { Paths.meetings.appendingPathComponent(id) }

    public static func newID(title: String, date: Date = Date()) -> String {
        let f = DateFormatter(); f.dateFormat = "yyyy-MM-dd-HHmmss"; f.locale = Locale(identifier: "en_US_POSIX")
        let slug = title.lowercased().map { $0.isLetter || $0.isNumber ? $0 : "-" }
            .reduce(into: "") { s, c in if !(c == "-" && s.hasSuffix("-")) { s.append(c) } }
            .trimmingCharacters(in: CharacterSet(charactersIn: "-"))
        return slug.isEmpty ? f.string(from: date) : "\(f.string(from: date))-\(slug.prefix(40))"
    }

    public static func create(_ m: Meeting) throws -> URL {
        let dir = folder(m.id)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        try save(m)
        return dir
    }

    public static func save(_ m: Meeting) throws {
        let dir = folder(m.id)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        let enc = JSONEncoder(); enc.outputFormatting = [.prettyPrinted, .sortedKeys]; enc.dateEncodingStrategy = .iso8601
        try enc.encode(m).write(to: dir.appendingPathComponent("meeting.json"), options: .atomic)
        if !m.segments.isEmpty {
            try Markdown.transcript(m).write(to: dir.appendingPathComponent("transcript.md"), atomically: true, encoding: .utf8)
        }
        if m.summary != nil {
            try Markdown.summary(m).write(to: dir.appendingPathComponent("summary.md"), atomically: true, encoding: .utf8)
        }
    }

    public static func load(_ id: String) throws -> Meeting {
        let dec = JSONDecoder(); dec.dateDecodingStrategy = .iso8601
        return try dec.decode(Meeting.self, from: Data(contentsOf: folder(id).appendingPathComponent("meeting.json")))
    }

    public static func all() -> [Meeting] {
        let fm = FileManager.default
        guard let ids = try? fm.contentsOfDirectory(atPath: Paths.meetings.path) else { return [] }
        return ids.compactMap { try? load($0) }.sorted { $0.createdAt > $1.createdAt }
    }

    public static func delete(_ id: String) throws { try FileManager.default.removeItem(at: folder(id)) }

    /// Case- and accent-insensitive search over titles, transcript text, summary and action items.
    public static func search(_ query: String, in meetings: [Meeting]? = nil) -> [(meeting: Meeting, hits: [String])] {
        let q = query.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil)
        guard !q.isEmpty else { return [] }
        func has(_ s: String) -> Bool { s.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil).contains(q) }
        return (meetings ?? all()).compactMap { m in
            var hits: [String] = []
            if has(m.title) { hits.append("title: \(m.title)") }
            for s in m.segments where has(s.text) { hits.append("[\(formatTime(s.start))] \(m.displayName(s.speaker)): \(s.text)") }
            if let su = m.summary {
                if has(su.summary) { hits.append("summary: \(su.summary)") }
                for a in su.actionItems where has(a.task) || has(a.owner ?? "") { hits.append("action: \(a.task)") }
            }
            return hits.isEmpty ? nil : (m, hits)
        }
    }
}

public enum Markdown {
    public static func transcript(_ m: Meeting) -> String {
        var out = "# \(m.title)\n\n"
        let f = DateFormatter(); f.dateStyle = .medium; f.timeStyle = .short
        out += "_\(f.string(from: m.createdAt)) · \(formatTime(m.duration)) · speakers: \(m.speakers.map(m.displayName).joined(separator: ", "))_\n\n"
        var last = ""
        for s in m.segments {
            let who = m.displayName(s.speaker)
            if who != last { out += "\n**\(who)** [\(formatTime(s.start))]\n"; last = who }
            out += "\(s.text)\n"
        }
        return out
    }

    public static func summary(_ m: Meeting) -> String {
        guard let s = m.summary else { return "" }
        var out = "# \(m.title): summary\n\n\(s.summary)\n"
        if !s.decisions.isEmpty { out += "\n## Decisions\n" + s.decisions.map { "- \($0)\n" }.joined() }
        out += "\n## Action items\n"
        if s.actionItems.isEmpty { out += "- (none found)\n" }
        for a in s.actionItems {
            out += "- [\(a.done ? "x" : " ")] **\(a.owner ?? "Unassigned")**: \(a.task)\(a.due.map { " (due \($0))" } ?? "")\n"
        }
        if !s.openQuestions.isEmpty { out += "\n## Open questions\n" + s.openQuestions.map { "- \($0)\n" }.joined() }
        out += "\n_Generated by \(s.provider)._\n"
        return out
    }

    /// Full export: summary + transcript in one file.
    public static func export(_ m: Meeting) -> String {
        (m.summary != nil ? summary(m) + "\n---\n\n" : "") + transcript(m)
    }
}
